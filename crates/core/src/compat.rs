/// The verdict for `feature` on `target`.
pub fn verdict(feature: Feature, target: Target) -> Verdict {
    RULES
        .iter()
        .find(|r| r.feature == feature && r.target == target)
        .map_or(Verdict::Supported, |r| r.verdict)
}

/// Whether a run with `features` may take `path`: no feature disables or
/// refuses it.
pub fn path_allowed(path: WritePath, features: &[Feature]) -> bool {
    features
        .iter()
        .all(|f| verdict(*f, Target::Path(path)) == Verdict::Supported)
}

/// The path a feature itself selects, when it does.
pub fn selected_path(feature: Feature) -> Option<WritePath> {
    match feature {
        Feature::ExactlyOnce => Some(WritePath::Watermark),
        Feature::Overwrite | Feature::GroupedOverwrite => Some(WritePath::OverwriteStaging),
        _ => None,
    }
}

/// Every refusal for a run with `features` against a sink with `sink`
/// capabilities: each (feature, target, reason) whose target is a path one of
/// the features selects, or a capability condition the sink meets.
pub fn refusals(
    features: &[Feature],
    sink: Option<&Capabilities>,
) -> Vec<(Feature, Target, &'static str)> {
    let selected: Vec<WritePath> = features.iter().filter_map(|f| selected_path(*f)).collect();
    RULES
        .iter()
        .filter(|r| features.contains(&r.feature))
        .filter(|r| match r.target {
            Target::Path(p) => selected.contains(&p),
            Target::Capability(c) => sink.is_some_and(|s| c.holds(s)),
        })
        .filter_map(|r| match r.verdict {
            Verdict::Refuse(reason) => Some((r.feature, r.target, reason)),
            _ => None,
        })
        .collect()
}

/// The reference page, generated from [`RULES`].
pub fn render_markdown() -> String {
    let mut out = String::new();
    out.push_str("# Feature compatibility\n\n");
    out.push_str(
        "<!-- Generated from `faucet_core::compat::RULES`. Do not edit by hand: run \
         `cargo test -p faucet-cli --test compat_doc -- --ignored regenerate`. -->\n\n",
    );
    out.push_str(
        "Which write path a run takes, and whether a combination is allowed at all, comes \
         from one table in `faucet_core::compat`. `Pipeline::run` picks the fastest path every \
         active feature supports, and `faucet validate` refuses a combination no path \
         honours before anything runs.\n\n\
         - **✓** — supported on that path.\n\
         - **falls back** — that path would skip the feature, so the run takes a slower path \
         that honours it (native → columnar → row).\n\
         - **refused** — the combination is rejected when the config is loaded.\n\n\
         A pair the table does not list is supported.\n\n",
    );
    out.push_str("## Write paths\n\n| Feature |");
    for p in WritePath::ALL {
        out.push_str(&format!(" {} |", p.label()));
    }
    out.push_str("\n|---|");
    for _ in WritePath::ALL {
        out.push_str("---|");
    }
    out.push('\n');
    for f in Feature::ALL {
        out.push_str(&format!("| {} |", f.label()));
        for p in WritePath::ALL {
            out.push_str(&format!(" {} |", cell(verdict(*f, Target::Path(*p)))));
        }
        out.push('\n');
    }
    out.push_str(
        "\nThe exactly-once watermark and overwrite staging columns apply only when the run \
         uses them (`delivery: exactly_once` against an idempotent sink, `write_mode: \
         overwrite`).\n\n## Sink capabilities\n\nA sink declares its capabilities \
         (`Sink::capabilities`, `faucet list --json`). These combinations depend on them:\n\n\
         | Feature | Sink | Verdict |\n|---|---|---|\n",
    );
    for r in RULES {
        if let Target::Capability(c) = r.target {
            out.push_str(&format!(
                "| {} | {} | {} |\n",
                r.feature.label(),
                c.label(),
                cell(r.verdict)
            ));
        }
    }
    out.push_str("\n## Refusal reasons\n\n");
    let mut seen: Vec<&str> = Vec::new();
    for r in RULES {
        if let Verdict::Refuse(reason) = r.verdict
            && !seen.contains(&reason)
        {
            seen.push(reason);
            let target = match r.target {
                Target::Path(p) => p.label(),
                Target::Capability(c) => c.label(),
            };
            out.push_str(&format!(
                "- {} × {}: {}.\n",
                r.feature.label(),
                target,
                reason
            ));
        }
    }
    out
}

fn cell(v: Verdict) -> &'static str {
    match v {
        Verdict::Supported => "✓",
        Verdict::DisablesPath => "falls back",
        Verdict::Refuse(_) => "refused",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::write_mode::WriteMode;

    #[test]
    fn unlisted_pairs_are_supported() {
        assert_eq!(
            verdict(F::Masking, Target::Path(P::Row)),
            Verdict::Supported
        );
        assert_eq!(
            verdict(F::Masking, Target::Path(P::Columnar)),
            Verdict::Supported
        );
        assert_eq!(verdict(F::Masking, Target::Path(P::Native)), D);
    }

    /// The table's constructors build the rows `verdict` reads.
    #[test]
    fn rule_constructors_build_table_rows() {
        let p = path(F::Overwrite, P::Watermark, R(EO_WITH_OVERWRITE));
        assert_eq!(p.target, Target::Path(P::Watermark));
        assert_eq!(verdict(p.feature, p.target), p.verdict);
        let c = cap(
            F::Cleanup,
            CapabilityCondition::NoCleanup,
            R(CLEANUP_UNSUPPORTED),
        );
        assert_eq!(verdict(c.feature, c.target), c.verdict);
    }

    #[test]
    fn row_path_honours_every_feature() {
        assert!(path_allowed(P::Row, Feature::ALL));
        for f in Feature::ALL {
            assert_eq!(verdict(*f, Target::Path(P::Row)), Verdict::Supported);
        }
    }

    #[test]
    fn path_selection_falls_back() {
        assert!(path_allowed(P::Native, &[F::Overwrite]));
        assert!(!path_allowed(P::Native, &[F::Overwrite, F::KeyedWrites]));
        assert!(path_allowed(P::Columnar, &[F::Masking, F::DlqPropagate]));
        assert!(!path_allowed(P::Columnar, &[F::DlqAll]));
        assert!(!path_allowed(P::Columnar, &[F::PolicyQuarantine]));
        assert!(path_allowed(P::Native, &[]));
    }

    #[test]
    fn refusals_apply_only_to_selected_paths_and_held_conditions() {
        assert!(refusals(&[F::DlqPropagate], None).is_empty());
        let r = refusals(&[F::ExactlyOnce, F::DlqPropagate], None);
        assert_eq!(r.len(), 1);
        assert_eq!(r[0].2, EO_WITH_DLQ);
        let r = refusals(&[F::ExactlyOnce, F::PolicyQuarantine], None);
        assert_eq!(r[0].2, EO_WITH_POLICY_QUARANTINE);
        assert_eq!(
            refusals(&[F::Overwrite, F::Cleanup], None)[0].2,
            OVERWRITE_WITH_CLEANUP
        );

        let drops = Capabilities::append_only_sink()
            .to_builder()
            .schema_report(SchemaReport::DropsUnknownFields)
            .build();
        let r = refusals(&[F::SchemaDrift, F::SchemaDriftFail], Some(&drops));
        assert_eq!(r.len(), 1);
        assert_eq!(r[0].1, Target::Capability(C::DropsUnknownFields));
        assert!(refusals(&[F::SchemaDriftFail], None).is_empty());

        let evolvable = Capabilities::builder()
            .write_modes([WriteMode::Append])
            .schema_evolution(true)
            .cleanup(true)
            .build();
        assert!(refusals(&[F::SchemaDriftEvolve, F::Cleanup], Some(&evolvable)).is_empty());
        assert_eq!(
            refusals(&[F::SchemaDriftEvolve, F::Cleanup], Some(&drops)).len(),
            2
        );
    }

    #[test]
    fn conditions_read_capabilities() {
        let none = Capabilities::append_only_sink();
        assert!(!C::DropsUnknownFields.holds(&none));
        assert!(C::NoSchemaEvolution.holds(&none));
        assert!(C::NoCleanup.holds(&none));
        for c in CapabilityCondition::ALL {
            assert!(!c.label().is_empty());
        }
    }

    #[test]
    fn every_feature_and_path_is_labelled_and_in_all() {
        for f in Feature::ALL {
            assert!(!f.label().is_empty());
        }
        for p in WritePath::ALL {
            assert!(!p.label().is_empty());
        }
        for r in RULES {
            assert!(Feature::ALL.contains(&r.feature));
            assert_ne!(r.verdict, Verdict::Supported, "only list exceptions");
        }
        assert_eq!(selected_path(F::Masking), None);
        assert_eq!(
            selected_path(F::GroupedOverwrite),
            Some(P::OverwriteStaging)
        );
    }

    #[test]
    fn rendered_page_lists_every_feature_and_reason() {
        let md = render_markdown();
        for f in Feature::ALL {
            assert!(md.contains(f.label()), "{f:?}");
        }
        assert!(md.contains(EO_WITH_POLICY_QUARANTINE));
        assert!(md.contains(DRIFT_FAIL_DROPS_FIELDS));
        assert!(
            md.contains("| `schema: { on_drift: fail }` | sink drops unknown fields | refused |")
        );
    }

    #[test]
    fn rules_serialize() {
        let v = serde_json::to_value(RULES[0]).unwrap();
        assert_eq!(v["feature"], "transforms");
        assert_eq!(v["target"]["kind"], "path");
        assert_eq!(v["verdict"]["verdict"], "disables_path");
    }
}
