//! Plan-time feature × write-path compatibility (RFC 0013, #883).
//!
//! Whether a guarantee holds depends on which path a run takes: the native
//! byte path, the columnar (Arrow) path, the row (`Value`) path, the
//! exactly-once watermark write, or the staged overwrite. This module is the
//! one table saying, for each pipeline feature, what happens on each path and
//! against each sink capability:
//!
//! - [`Verdict::Supported`] — the feature holds on that path.
//! - [`Verdict::DisablesPath`] — the path would skip the feature, so the
//!   pipeline falls back to a slower path that honours it.
//! - [`Verdict::Refuse`] — no path honours the combination; it is refused
//!   when the config is loaded (and again when the pipeline starts).
//!
//! [`Pipeline::run`](crate::Pipeline::run) selects its path through
//! [`path_allowed`]; the CLI's load-time gates read [`refusals`]; the
//! reference page `docs/book/src/reference/compatibility.md` is generated by
//! [`render_markdown`]. A combination not listed is supported.

use crate::capabilities::{Capabilities, SchemaReport};
use serde::Serialize;

/// A pipeline feature (or one of its modes) that constrains the write path.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum Feature {
    /// A transform chain on the source.
    Transforms,
    /// A PII masking policy.
    Masking,
    /// A masking rule that changes a column's type by value (value detector,
    /// number/bool coerced to a string).
    MaskingRetypesByValue,
    /// Data-quality checks.
    Quality,
    /// A data contract.
    Contract,
    /// Any `schema:` drift policy.
    SchemaDrift,
    /// `schema.on_drift: fail`.
    SchemaDriftFail,
    /// `schema.on_drift: evolve`.
    SchemaDriftEvolve,
    /// A DLQ with `on_batch_error: propagate`.
    DlqPropagate,
    /// A DLQ with `on_batch_error: dlq_all`.
    DlqAll,
    /// `delivery: exactly_once` through the atomic watermark.
    ExactlyOnce,
    /// `write_mode: upsert|delete` with a `key`.
    KeyedWrites,
    /// `write_mode: overwrite`.
    Overwrite,
    /// A fan-out overwrite whose rows share one staged destination.
    GroupedOverwrite,
    /// Adaptive batch sizing.
    Adaptive,
    /// A `resilience:` retry / circuit-breaker policy.
    Resilience,
    /// Scoped cleanup (`complete_for` with `on_missing: delete`).
    Cleanup,
    /// A data-flow policy rule with `on_runtime: quarantine`.
    PolicyQuarantine,
    /// A data-flow policy runtime backstop (any rule).
    Policy,
    /// A run budget (`budget:` ceilings).
    Budget,
    /// Column profiling (`profiling:`).
    Profiling,
    /// `_faucet_*` metadata columns (`metadata_columns:`).
    MetadataColumns,
}

